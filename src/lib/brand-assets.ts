/**
 * The official wordmarks, inlined.
 *
 * WHY BASE64 AND NOT A FILE PATH. pptxgenjs and jsPDF both accept a path, and
 * both would work locally. On Vercel the document renderers run inside a
 * bundled server function whose filesystem contains what the bundler traced —
 * and neither library's `path` argument is a static reference the tracer can
 * see, so `public/branding/*.png` is exactly the kind of asset that is present
 * in dev and absent in production. The failure is a deck that generates with a
 * blank corner, which nobody notices until a customer has it.
 *
 * The PNGs are also in `public/branding/` for the app to serve normally; these
 * are generated from those same files. Regenerate both together.
 */

